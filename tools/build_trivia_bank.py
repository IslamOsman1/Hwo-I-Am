def build():
    bank = []
    for category, text in DATA.items():
        for line in text.strip().splitlines():
            level = 'medium' if line.startswith('@') else 'easy'
            prompt, aliases, explanation = line.lstrip('@').split('|')
            bank.append(dict(id=f'q{len(bank) + 1:04}', category=category,
                             level=level, prompt=prompt, answers=aliases.split(','),
                             explanation=explanation))
    for a in range(2, 16):
        for b in range(2, 12):
            result = a * b
            bank.append(dict(id=f'mul{a}_{b}', category='حساب',
                             level='easy' if a <= 7 and b <= 7 else 'medium',
                             prompt=f'ناتج {a} × {b} كام؟', answers=[str(result)],
                             explanation=f'{a} × {b} = {result}'))
    for a in range(11, 31):
        b = a - 7
        bank.append(dict(id=f'add{a}', category='حساب', level='easy',
                         prompt=f'ناتج {a} + {b} كام؟', answers=[str(a + b)],
                         explanation=f'{a} + {b} = {a + b}'))
    assert len({q['id'] for q in bank}) == len(bank)
    assert len({q['prompt'] for q in bank}) == len(bank)
    output = ROOT / 'server/data/questions.json'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{len(bank)} questions; easy={sum(q["level"] == "easy" for q in bank)}')


if __name__ == '__main__':
    build()
